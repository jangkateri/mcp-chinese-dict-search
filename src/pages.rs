//! Clickable citation pages: one Markdown file per retrieved entry.
//!
//! A hyperlink cannot call an MCP tool, so a clickable citation has to point at
//! content that already exists. When a page directory is configured, every
//! `get_entry` result is also written there and the result names the file. VS
//! Code linkifies an absolute path and opens it in the editor; terminals that
//! follow OSC 8 links can use the `file://` link printed beside it.

use std::collections::HashMap;
use std::fs;
use std::path::{Path, PathBuf};

use crate::dictionary::{Dictionary, EntryRequest, EntryResponse, Scope};
use crate::server::SERVER_VERSION;
use crate::tools::{DEFAULT_MAX_CHARS, render_entry_page, render_entry_page_linked};

/// The directory citation pages are written to.
#[derive(Debug, Clone)]
pub struct Pages {
    directory: PathBuf,
}

impl Pages {
    /// Resolve `directory` to an absolute path and create it.
    pub fn new(directory: &Path) -> std::io::Result<Self> {
        let directory = std::path::absolute(directory)?;
        fs::create_dir_all(&directory)?;
        Ok(Self { directory })
    }

    pub fn directory(&self) -> &Path {
        &self.directory
    }

    /// Write the page for `response` and return the lines naming it. Pages for
    /// the entry's cross-references are written too, so the page's links point
    /// at files that exist in the same directory.
    pub fn attach(&self, dictionary: &Dictionary, response: &EntryResponse) -> String {
        let links = self.write_cross_reference_pages(dictionary, response);
        let text = render_entry_page_linked(response, &|link| {
            link.target_anchor
                .as_ref()
                .and_then(|anchor| links.get(anchor).cloned())
        });
        self.attach_text(response, &text)
    }

    /// Write the page for `term` without naming it in a result, so a suggestion
    /// can carry a clickable target. Returns the absolute path.
    pub(crate) fn page_for(&self, dictionary: &Dictionary, term: &str) -> Option<PathBuf> {
        let response = dictionary
            .entry(&EntryRequest {
                term: term.to_owned(),
                source: Scope::All,
                max_chars: DEFAULT_MAX_CHARS,
            })
            .ok()?;
        let text = render_entry_page(&response);
        self.write(&response, &text).ok()
    }

    fn attach_text(&self, response: &EntryResponse, text: &str) -> String {
        match self.write(response, text) {
            Ok(path) => {
                let mut lines = vec![format!("Entry page: {}", path.display())];
                if let Some(url) = file_url(&path) {
                    lines.push(format!("Clickable link: [open the entry]({url})"));
                }
                lines.join("\n")
            }
            Err(error) => format!("[citation page could not be written: {error}]"),
        }
    }

    /// Write one page per resolved cross-reference and return `anchor → file
    /// name`. Those pages keep plain cross-references: their own targets may
    /// have no page, and a link to a missing file is the failure to avoid.
    fn write_cross_reference_pages(
        &self,
        dictionary: &Dictionary,
        response: &EntryResponse,
    ) -> HashMap<String, String> {
        let mut names = HashMap::new();
        for link in &response.cross_references {
            let Some(anchor) = &link.target_anchor else {
                continue;
            };
            let Ok(target) = dictionary.entry(&EntryRequest {
                term: anchor.clone(),
                source: Scope::All,
                max_chars: DEFAULT_MAX_CHARS,
            }) else {
                continue;
            };
            let text = render_entry_page(&target);
            if self.write(&target, &text).is_ok() {
                names.insert(anchor.clone(), page_file_name(&target));
            }
        }
        names
    }

    fn write(&self, response: &EntryResponse, text: &str) -> std::io::Result<PathBuf> {
        let path = self.directory.join(page_file_name(response));
        let page = format!(
            "{text}\n\n---\nGenerated by mcp-chinese-dict-search {SERVER_VERSION} from `{}`. Local derived \
             file; do not redistribute.\n",
            response.citation
        );
        fs::write(&path, page)?;
        Ok(path)
    }
}

/// `source-id.md`: unique for main anchors, appendix IDs, and weights sections.
fn page_file_name(response: &EntryResponse) -> String {
    let suffix = response
        .id
        .clone()
        .or_else(|| {
            response
                .citation
                .rsplit_once('#')
                .map(|(_, anchor)| anchor.to_owned())
        })
        .unwrap_or_else(|| response.term.clone());
    let mut key = sanitize(&suffix);
    if key.is_empty() {
        key = "entry".to_owned();
    }
    format!("{}-{key}.md", response.source.as_str())
}

fn sanitize(value: &str) -> String {
    let key: String = value
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || matches!(character, '.' | '-' | '_') {
                character
            } else {
                '-'
            }
        })
        .collect();
    key.split('-')
        .filter(|part| !part.is_empty())
        .collect::<Vec<_>>()
        .join("-")
}

/// A `file://` URL for `path`, percent-encoding spaces and non-ASCII bytes.
fn file_url(path: &Path) -> Option<String> {
    let text = path.to_str()?.replace('\\', "/");
    // A Unix path supplies its own leading slash; a Windows drive does not.
    let mut url = if text.starts_with('/') {
        String::from("file://")
    } else {
        String::from("file:///")
    };
    for byte in text.bytes() {
        let safe =
            byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'.' | b'_' | b'~' | b'/' | b':');
        if safe {
            url.push(char::from(byte));
        } else {
            url.push_str(&format!("%{byte:02X}"));
        }
    }
    Some(url)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dictionary::{EntryAliases, Source};

    fn response(source: Source, id: Option<&str>, term: &str, citation: &str) -> EntryResponse {
        EntryResponse {
            source,
            term: term.to_owned(),
            id: id.map(str::to_owned),
            aliases: EntryAliases::default(),
            content: "A short definition.".to_owned(),
            cross_references: Vec::new(),
            related: Vec::new(),
            redirected_from: None,
            citation: citation.to_owned(),
            source_file: None,
            line: None,
            truncated: false,
            total_chars: 18,
        }
    }

    fn directory(label: &str) -> PathBuf {
        let directory = std::env::temp_dir().join(format!(
            "mcp-chinese-dict-pages-test-{}-{label}",
            std::process::id()
        ));
        let _ = fs::remove_dir_all(&directory);
        directory
    }

    #[test]
    fn page_keys_are_stable_per_source_and_identifier() {
        assert_eq!(
            page_file_name(&response(
                Source::Dictionary,
                None,
                "alpha swelling",
                "Test Dictionary, 08-a.md#a1ASW"
            )),
            "dictionary-a1ASW.md"
        );
        assert_eq!(
            page_file_name(&response(
                Source::Meridian,
                Some("AA-1"),
                "Jia Three Li",
                "Test Dictionary, 34-appendix-1-Meridian.md:AA-1"
            )),
            "meridian-AA-1.md"
        );
        assert_eq!(
            page_file_name(&response(
                Source::Formulas,
                Some("01.01.01"),
                "Jia Decoction",
                "Test Dictionary, 36-appendix-3-Formulas.md:01.01.01"
            )),
            "formulas-01.01.01.md"
        );
        assert_eq!(
            page_file_name(&response(
                Source::Dictionary,
                None,
                "beta aspect",
                "Test Dictionary, 08-a.md:12"
            )),
            "dictionary-beta-aspect.md"
        );
    }

    #[test]
    fn the_link_percent_encodes_spaces_and_keeps_drive_letters() {
        let url = file_url(Path::new(
            "C:\\Users\\Example\\AppData\\Local\\Temp\\pages\\dictionary-a1ASW.md",
        ))
        .expect("a Windows path converts");
        assert_eq!(
            url,
            "file:///C:/Users/Example/AppData/Local/Temp/pages/dictionary-a1ASW.md"
        );
    }

    #[test]
    fn writing_a_page_names_it_in_the_result() {
        let directory = directory("write");
        let pages = Pages::new(&directory).expect("pages directory is created");
        let entry = response(
            Source::Dictionary,
            None,
            "alpha swelling",
            "Test Dictionary, 08-a.md#a1ASW",
        );

        let lines = pages.attach_text(&entry, &render_entry_page(&entry));
        assert!(lines.contains("Entry page: "));
        assert!(lines.contains("Clickable link: [open the entry](file:///"));

        let path = pages.directory().join("dictionary-a1ASW.md");
        let page = fs::read_to_string(&path).expect("the page is written");
        assert!(page.starts_with("# alpha swelling\n"));
        assert!(
            page.contains("`Test Dictionary, 08-a.md#a1ASW`"),
            "the citation is shown as code, not a dead relative link: {page}"
        );
        assert!(page.contains("A short definition."));
        assert!(!page.contains("tcm citation"), "pages omit the reopen hint");

        let _ = fs::remove_dir_all(&directory);
    }

    #[test]
    fn a_write_failure_degrades_to_a_note() {
        let directory = directory("failure");
        let pages = Pages::new(&directory).expect("pages directory is created");
        fs::remove_dir_all(&directory).expect("directory is removed");
        fs::write(&directory, b"not a directory").expect("a file occupies the path");

        let entry = response(
            Source::Dictionary,
            None,
            "alpha swelling",
            "Test Dictionary, 08-a.md#a1ASW",
        );
        let lines = pages.attach_text(&entry, &render_entry_page(&entry));
        assert!(
            lines.starts_with("[citation page could not be written"),
            "got {lines}"
        );

        let _ = fs::remove_file(&directory);
    }
}
